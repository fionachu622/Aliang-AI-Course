import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readFileSync,
  writeFileSync,
} from 'node:fs';
import {execFileSync} from 'node:child_process';
import {dirname, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const transcriptDir = resolve(projectRoot, '../../build/lesson1_video');
const activeAudioDir = resolve(projectRoot, 'public/audio');
const generatedAudioDir = resolve(projectRoot, 'public/audio-custom');
const backupAudioDir = resolve(projectRoot, 'public/audio-system-tingting');

const apiKey = process.env.ELEVENLABS_API_KEY;
const voiceId = process.env.ELEVENLABS_VOICE_ID;
const modelId = process.env.ELEVENLABS_MODEL_ID || 'eleven_multilingual_v2';

if (!apiKey) throw new Error('Missing ELEVENLABS_API_KEY in .env');
if (!voiceId) throw new Error('Missing ELEVENLABS_VOICE_ID in .env');

const scenes = Array.from({length: 10}, (_, index) => {
  const id = String(index + 1).padStart(2, '0');
  const source = resolve(transcriptDir, `narration_${id}.txt`);
  const text = readFileSync(source, 'utf8')
    .replace(/^\s*•\s*/gm, '')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
  return {id, text};
});

const characterCount = scenes.reduce((sum, item) => sum + item.text.length, 0);
console.log(`10 scenes, ${characterCount} characters will be synthesized.`);

if (!process.argv.includes('--confirm-cost')) {
  throw new Error(
    'No API request was made. Re-run with --confirm-cost after checking your ElevenLabs quota.',
  );
}

mkdirSync(generatedAudioDir, {recursive: true});

for (const [index, scene] of scenes.entries()) {
  console.log(`[${index + 1}/10] Generating scene ${scene.id}...`);
  const response = await fetch(
    `https://api.elevenlabs.io/v1/text-to-speech/${encodeURIComponent(voiceId)}?output_format=mp3_44100_128`,
    {
      method: 'POST',
      headers: {
        'xi-api-key': apiKey,
        'Content-Type': 'application/json',
        Accept: 'audio/mpeg',
      },
      body: JSON.stringify({
        text: scene.text,
        model_id: modelId,
        voice_settings: {
          stability: 0.58,
          similarity_boost: 0.85,
          style: 0.2,
          use_speaker_boost: true,
          speed: 1,
        },
      }),
    },
  );

  if (!response.ok) {
    throw new Error(
      `Scene ${scene.id} failed (${response.status}): ${await response.text()}`,
    );
  }

  writeFileSync(
    resolve(generatedAudioDir, `${scene.id}.mp3`),
    Buffer.from(await response.arrayBuffer()),
  );
}

const durations = scenes.map(({id}) => {
  const value = execFileSync(
    'ffprobe',
    [
      '-v',
      'error',
      '-show_entries',
      'format=duration',
      '-of',
      'default=noprint_wrappers=1:nokey=1',
      resolve(generatedAudioDir, `${id}.mp3`),
    ],
    {encoding: 'utf8'},
  ).trim();
  return Number(value);
});

mkdirSync(backupAudioDir, {recursive: true});
for (const {id} of scenes) {
  const active = resolve(activeAudioDir, `${id}.mp3`);
  const backup = resolve(backupAudioDir, `${id}.mp3`);
  if (existsSync(active) && !existsSync(backup)) copyFileSync(active, backup);
}

for (const {id} of scenes) {
  copyFileSync(
    resolve(generatedAudioDir, `${id}.mp3`),
    resolve(activeAudioDir, `${id}.mp3`),
  );
}

writeFileSync(
  resolve(projectRoot, 'src/generatedVoiceover.ts'),
  `// Generated by scripts/generate-voiceover.mjs\nexport const CUSTOM_AUDIO_DURATIONS: readonly number[] | null = ${JSON.stringify(durations, null, 2)};\n`,
);

writeFileSync(
  resolve(generatedAudioDir, 'manifest.json'),
  `${JSON.stringify(
    {
      generatedAt: new Date().toISOString(),
      provider: 'ElevenLabs',
      voiceId,
      modelId,
      durations,
    },
    null,
    2,
  )}\n`,
);

console.log('Custom voice audio is active in public/audio/.');
console.log('Original system audio is preserved in public/audio-system-tingting/.');
console.log('Run npm run typecheck, then preview in Remotion Studio.');
